// Scroll storytelling ("the page becomes a musical score as you scroll").
//
// #home holds a tall spacer (.story-spacer, see style.css) beneath the
// visually-unchanged hero, so scrolling it produces a 0..1 progress value
// (storyProgress) via the classic sticky-pin formula: how far the section's
// top has scrolled past the viewport top, divided by its scrollable range.
// Each movement below just owns a slice of that 0..1 range and fades/moves
// within it -- no timers, no IntersectionObserver thresholds to keep in
// sync, and scrolling back up reverses everything for free.
// ---------------------------------------------------------------------
const heroStage = document.getElementById('heroStage');
const scrollStory = document.getElementById('scrollStory');
const scrollCue = document.getElementById('scrollCue');
const soundToggle = document.getElementById('soundToggle');
const soundToggleLabel = document.getElementById('soundToggleLabel');

const STORY_MOVEMENTS = [
  { id: 'silence',   start: .12, end: .25 },
  { id: 'listening', start: .25, end: .38 },
  { id: 'breath',    start: .38, end: .52 },
  { id: 'rubato',    start: .52, end: .67 },
  { id: 'cantabile', start: .67, end: .80 },
  { id: 'resonance', start: .80, end: .92 },
  { id: 'dacapo',    start: .92, end: 1 }
];
const movementEls = {};
STORY_MOVEMENTS.forEach(m => { movementEls[m.id] = scrollStory?.querySelector(`[data-movement="${m.id}"]`); });

const clamp = (v, min, max) => Math.min(max, Math.max(min, v));
const lerp = (a, b, t) => a + (b - a) * t;

let reducedMotion = matchMedia('(prefers-reduced-motion: reduce)');
let prefersReducedMotion = reducedMotion.matches;
function motionPreferenceChanged(e) {
  prefersReducedMotion = e.matches;
  smoothVelocity = 0;
  requestTick();
}
reducedMotion.addEventListener?.('change', motionPreferenceChanged);
const compactScreen = matchMedia('(max-width: 820px)');

// Entrance/hold/exit envelope shared by every movement: fade+rise in over the
// first ENTER fraction of the movement's own local progress, hold at full
// opacity, then fade out over the remainder -- "silence -> appearance ->
// movement -> disappearance -> silence".
const ENTER = .22, HOLD_END = .72;
const ENTRANCE_PX = 24;
function envelope(t) {
  if (t <= 0 || t >= 1) return 0;
  if (t < ENTER) return t / ENTER;
  if (t < HOLD_END) return 1;
  return 1 - (t - HOLD_END) / (1 - HOLD_END);
}

// RUBATO: scroll velocity nudges translate/letter-spacing by a small, capped
// amount on top of the normal envelope, decaying back to rest once scrolling
// stops -- the visitor unconsciously "plays" the tempo. Disabled entirely
// under prefers-reduced-motion.
const RUBATO_MAX_TRANSLATE = 10;
const RUBATO_MAX_LETTER_SPACING = .05;

function renderResonance(el, t) {
  const p1 = el.querySelector('.story-text--resonance-1');
  const p2 = el.querySelector('.story-text--resonance-2');
  if (!p1 || !p2) return;
  const in1 = clamp(t / .15, 0, 1);
  const out1 = clamp((t - .42) / .4, 0, 1);
  const o1 = clamp(in1 - out1, 0, 1);
  p1.style.opacity = o1.toFixed(3);
  p1.style.letterSpacing = prefersReducedMotion ? '' : (out1 * .08).toFixed(2) + 'em';

  const in2 = clamp((t - .3) / .15, 0, 1);
  const out2 = clamp((t - .8) / .2, 0, 1);
  const o2 = clamp(in2 - out2, 0, 1);
  p2.style.opacity = o2.toFixed(3);
}

function renderStaff(el, t) {
  const lines = el.querySelectorAll('.story-staff span');
  if (!lines.length) return;
  lines.forEach((line, i) => {
    if (prefersReducedMotion) { line.style.transform = 'scaleX(1)'; line.style.opacity = envelope(t).toFixed(3); return; }
    const s = .08 + i * .07;
    const drawn = clamp((t - s) / .3, 0, 1);
    line.style.transform = `scaleX(${drawn.toFixed(3)})`;
    line.style.opacity = Math.min(drawn, envelope(t)).toFixed(3);
  });
}

function applyMovement(m, el, t, velocity) {
  if (!el) return;
  const visible = t > 0 && t < 1;
  el.style.visibility = visible ? 'visible' : 'hidden';
  el.setAttribute('aria-hidden', String(!visible));
  if (m.id === 'resonance') {
    // Owns its own two-line opacity/letter-spacing timing; the wrapping
    // element itself is just an on/off gate for the (already-faded) label.
    el.style.opacity = t > 0 && t < 1 ? '1' : '0';
    const label = el.querySelector('.story-label');
    if (label) label.style.opacity = envelope(t).toFixed(3);
    renderResonance(el, t);
    return;
  }

  const o = envelope(t);
  el.style.opacity = o.toFixed(3);

  let translateY = prefersReducedMotion ? 0 : (1 - Math.min(t / ENTER, 1)) * (compactScreen.matches ? 8 : ENTRANCE_PX);
  let translateX = 0;
  let extraLetterSpacing = 0;

  if (m.id === 'rubato' && !prefersReducedMotion && !compactScreen.matches) {
    translateY += velocity * RUBATO_MAX_TRANSLATE;
    translateX += velocity * RUBATO_MAX_TRANSLATE * .4;
    extraLetterSpacing = velocity * RUBATO_MAX_LETTER_SPACING;
  }

  if (m.id === 'cantabile' && !prefersReducedMotion) translateX = Math.sin(t * Math.PI) * (compactScreen.matches ? 2 : 6);

  el.style.transform = `translate3d(${translateX.toFixed(2)}px, ${translateY.toFixed(2)}px, 0)`;
  const textEl = el.querySelector('.story-text');
  if (textEl) textEl.style.letterSpacing = extraLetterSpacing ? extraLetterSpacing.toFixed(4) + 'em' : '';

  if (m.id === 'breath') renderStaff(el, t);
}

let rafId = null;
let lastScrollY = window.scrollY;
let lastTime = performance.now();
let smoothVelocity = 0;
let lastActivityTime = performance.now();
let cueReleased = false;

// Cache geometry on layout changes; scroll frames only write visual properties.
let storyTop = 0;
let storyDistance = 1;
function measureStory() {
  if (!heroStage || hero.classList.contains('hidden')) return;
  storyTop = hero.getBoundingClientRect().top + window.scrollY;
  storyDistance = Math.max(1, hero.offsetHeight - window.innerHeight);
}
function renderStory() {
  if (!heroStage || hero.classList.contains('hidden')) return;
  const progress = clamp((window.scrollY - storyTop) / storyDistance, 0, 1);
  STORY_MOVEMENTS.forEach(m => {
    const t = clamp((progress - m.start) / (m.end - m.start), 0, 1);
    applyMovement(m, movementEls[m.id], t, smoothVelocity);
  });
  if (scrollCue) scrollCue.classList.toggle('is-visible', cueReleased && progress < .03);
  if (soundToggle) soundToggle.classList.toggle('is-visible', hasAudio && progress > .12 && progress < .99);

  const activeMovement = STORY_MOVEMENTS.find(m => progress > m.start && progress < m.end)?.id || null;
  if (activeMovement !== currentStoryMovement) {
    currentStoryMovement = activeMovement;
    stopMovementSound();
  }
  // Wait until the visitor is inside a movement, away from its boundary.
  const movement = STORY_MOVEMENTS.find(m => m.id === activeMovement);
  if (movement && (progress - movement.start) / (movement.end - movement.start) > .08) {
    playMovementSound(activeMovement);
  }
}

function tick(now) {
  const dt = Math.max(now - lastTime, 1);
  const dy = window.scrollY - lastScrollY;
  lastTime = now;
  lastScrollY = window.scrollY;
  const rawVelocity = prefersReducedMotion ? 0 : Math.min(Math.abs(dy) / dt / 3, 1);
  if (rawVelocity > .001) lastActivityTime = now;
  smoothVelocity = lerp(smoothVelocity, rawVelocity, .18);

  renderStory();

  if (smoothVelocity > .002 || now - lastActivityTime < 60) {
    rafId = requestAnimationFrame(tick);
  } else {
    smoothVelocity = 0;
    renderStory();
    rafId = null;
  }
}
function requestTick() {
  if (rafId == null) {
    lastTime = performance.now();
    rafId = requestAnimationFrame(tick);
  }
}
window.addEventListener('scroll', requestTick, { passive: true });
function resizeStory() { measureStory(); requestTick(); }
window.addEventListener('resize', resizeStory, { passive: true });
window.visualViewport?.addEventListener('resize', resizeStory, { passive: true });

// The scroll cue only appears once the existing header/hero entrance
// choreography (see the fadeUp/heroReveal animations in style.css, which run
// through roughly 1.7s) has settled, so it never competes with it -- then it
// fades back out the moment the visitor actually starts scrolling.
const cueTimer = setTimeout(() => { cueReleased = true; requestTick(); }, 1800);

// ---- Optional ambient sound: real, local recordings only ----------------
// Paths are configured separately in story-audio.js. No request is made until
// a visitor explicitly enables sound. An empty configuration hides the control.
const MOVEMENT_AUDIO = window.PIANO_STORY_AUDIO || {};
const hasAudio = Object.values(MOVEMENT_AUDIO).some(src => typeof src === 'string' && src.startsWith('assets/audio/'));
let currentStoryMovement = null;
let soundEnabled = false;
let activeAudio = null;
let playedMovement = null;
const lastPlayedAt = new Map();
const fadingAudio = new Map();
const AUDIO_COOLDOWN_MS = 6000;

function fadeOutAndStop(audio) {
  if (!audio || fadingAudio.has(audio)) return;
  const initialVolume = audio.volume;
  const started = performance.now();
  function step(now) {
    const remaining = Math.max(0, 1 - (now - started) / 350);
    audio.volume = initialVolume * remaining;
    if (remaining > 0) fadingAudio.set(audio, requestAnimationFrame(step));
    else { audio.pause(); fadingAudio.delete(audio); }
  }
  fadingAudio.set(audio, requestAnimationFrame(step));
}
function stopMovementSound() {
  fadeOutAndStop(activeAudio);
  activeAudio = null;
  playedMovement = null;
}
function playMovementSound(id) {
  if (!soundEnabled || playedMovement === id || document.hidden || currentSection) return;
  const src = MOVEMENT_AUDIO[id];
  if (typeof src !== 'string' || !src.startsWith('assets/audio/')) return;
  const now = performance.now();
  if (now - (lastPlayedAt.get(id) ?? -Infinity) < AUDIO_COOLDOWN_MS) return;
  playedMovement = id;
  lastPlayedAt.set(id, now);
  const audio = new Audio(src);
  audio.volume = .75;
  activeAudio = audio;
  audio.play().catch(() => {
    if (activeAudio !== audio) return;
    soundEnabled = false;
    stopMovementSound();
    updateSoundToggleLabel();
  });
}
function updateSoundToggleLabel() {
  if (!soundToggle || !soundToggleLabel) return;
  const labels = copy[currentLang].story;
  soundToggleLabel.textContent = labels[soundEnabled ? 'soundOn' : 'soundOff'];
  soundToggle.setAttribute('aria-label', labels[soundEnabled ? 'soundDisable' : 'soundEnable']);
  soundToggle.setAttribute('aria-pressed', String(soundEnabled));
  soundToggle.hidden = !hasAudio;
}
function toggleStorySound() {
  if (!hasAudio) return;
  soundEnabled = !soundEnabled;
  updateSoundToggleLabel();
  if (!soundEnabled) stopMovementSound();
  else if (currentStoryMovement) playMovementSound(currentStoryMovement);
}
function suspendStory() {
  soundEnabled = false;
  stopMovementSound();
  for (const [audio, frame] of fadingAudio) { cancelAnimationFrame(frame); audio.pause(); }
  fadingAudio.clear();
  currentStoryMovement = null;
  smoothVelocity = 0;
  if (rafId !== null) cancelAnimationFrame(rafId);
  rafId = null;
  updateSoundToggleLabel();
}
function visibilityChanged() {
  if (document.hidden) suspendStory();
  else resizeStory();
}
function destroyStory() {
  suspendStory();
  clearTimeout(cueTimer);
  window.removeEventListener('scroll', requestTick);
  window.removeEventListener('resize', resizeStory);
  window.visualViewport?.removeEventListener('resize', resizeStory);
  reducedMotion.removeEventListener?.('change', motionPreferenceChanged);
  document.removeEventListener('visibilitychange', visibilityChanged);
  soundToggle?.removeEventListener('click', toggleStorySound);
  window.removeEventListener('pagehide', storyPageHidden);
  window.removeEventListener('pageshow', resizeStory);
}
function storyPageHidden(event) {
  if (event.persisted) suspendStory();
  else destroyStory();
}
soundToggle?.addEventListener('click', toggleStorySound);
document.addEventListener('visibilitychange', visibilityChanged);
window.addEventListener('pagehide', storyPageHidden);
window.addEventListener('pageshow', resizeStory);
measureStory();
requestTick();

